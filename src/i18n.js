// Langue de l'interface : français (texte du code) ou anglais (dictionnaire ci-dessous).
// tr("texte français", { n: 3 }) rend le texte dans la langue choisie ; {n} est remplacé par la valeur.

export const LANGS = [['fr', 'Français'], ['en', 'English']];

let lang = 'fr';

export function getLang() { return lang; }
export function setLang(l) { lang = l === 'en' ? 'en' : 'fr'; }
export function systemLang() {
  const l = (typeof navigator !== 'undefined' && navigator.language) || 'fr';
  return /^fr/i.test(l) ? 'fr' : 'en';
}

export function tr(fr, vars) {
  let s = lang === 'en' && EN[fr] != null ? EN[fr] : fr;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// Table de libellés traduite à la lecture (pour les constantes de module).
export function labels(obj) {
  return new Proxy(obj, { get: (o, k) => (typeof o[k] === 'string' ? tr(o[k]) : o[k]) });
}

